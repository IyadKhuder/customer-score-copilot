@dataclass
class ToolCall:
    id: str
    name: str
    arguments: dict


@dataclass
class Reply:
    text: str = ""
    tool_calls: list = field(default_factory=list)


class ScriptedClient:
    def __init__(self, final_payload):
        self.payload = copy.deepcopy(final_payload)
        self.calls = 0
        self.prompt = None

    def chat(self, *, messages, tools):
        self.calls += 1
        self.prompt = messages[0]["content"]
        return Reply(tool_calls=[
            ToolCall(id="history", name="get_history", arguments={"account_id": ACCOUNT}),
            ToolCall(id="policy", name="retrieve_policy", arguments={"query": "POL-002"}),
        ])

    def continue_with_tool_results(self, *, assistant_response, tool_results, tools):
        self.calls += 1
        assert len(tool_results) == 2
        return Reply(text=json.dumps(self.payload))


def run_scripted(payload=None, audit_override=None):
    data = copy.deepcopy(declared_claims() if payload is None else payload)
    client = ScriptedClient(data)
    kwargs = {"publication_mode": "claims_first", "claim_scope": CLAIM_SCOPE,
              "expected_account_id": ACCOUNT, "expected_period": PERIOD,
              "expected_market": MARKET, "verbose": False}

    def guarded_verifier(raw, recorded_evidence, *, narrative_mode):
        assert narrative_mode == "claims_first"
        assert json.loads(raw) == data
        assert len(recorded_evidence) == 2
        return copy.deepcopy(audit_override if audit_override is not None
                             else verified_audit(data))

    with patch.dict(agent.ALL_TOOL_DISPATCH, {
        "get_history": lambda account_id: copy.deepcopy(ROWS) if account_id == ACCOUNT else [],
        "retrieve_policy": lambda **kwargs: copy.deepcopy(POLICY_PASSAGES),
    }), patch.object(agent, "verify_structured_response", side_effect=guarded_verifier):
        result = agent.run_agent("Summarize CF-001-like synthetic history", client, **kwargs)
    assert client.calls == 2
    return result


def test_agent_publishes_only_deterministic_text_with_no_limitations():
    result = run_scripted()
    assert result["publishable"] is True
    assert result["next_action"] == "publish"
    assert result["verification"]["rendering"]["status"] == "passed"
    assert result["verification"]["limitations"] == []
    assert result["answer"] == render()
    assert "UNPUBLISHED" not in result["answer"]


def test_agent_preserves_and_blocks_disclaimed_real_evidence_gap():
    data = declared_claims()
    data["limitations"] = ["Missing necessary evidence for a required claim"]
    result = run_scripted(data)
    assert result["publishable"] is False
    assert "COMPOSITION_UNSUPPORTED" in result["reason_codes"]
    assert result["next_action"] == "revise_response"
    assert result["verification"]["limitations"] == data["limitations"]
    assert "UNPUBLISHED" not in result["answer"]


def test_agent_remains_fail_closed_even_if_model_uses_routine_caveat_in_limitations():
    data = declared_claims()
    data["limitations"] = ["Unable to check whether operational warning was registered"]
    result = run_scripted(data)
    assert result["publishable"] is False
    assert result["verification"]["rendering"]["reason"] == "Unresolved audit issues or limitations"
    assert "COMPOSITION_UNSUPPORTED" in result["reason_codes"]


def test_agent_missing_claim_still_not_publishable_with_empty_limitations():
    data = declared_claims()
    data["policy_claims"].pop()
    incomplete = verified_audit(data)
    incomplete["status"] = "incomplete"
    incomplete["policy"]["status"] = "incomplete"
    result = run_scripted(data, audit_override=incomplete)
    assert result["publishable"] is False
    assert "UNPUBLISHED" not in result["answer"]


def test_agent_retains_caller_context_and_policy_retrieval_requirement():
    result = run_scripted()
    assert result["publishable"] is True
    assert any(item["tool_name"] == "get_history" for item in result["tool_evidence"])
    assert any(item["tool_name"] == "retrieve_policy" for item in result["tool_evidence"])
    assert "UNPUBLISHED" not in result["answer"]
