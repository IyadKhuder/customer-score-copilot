MARKET = 1
HISTORY_MONTHS = ["2024-12-01", "2025-01-01", "2025-02-01", "2025-03-01", PERIOD]
HISTORY_SCORES = [286, 282, 275, 267, 271]
ROWS = [dict(period=month, score=value, bin=6, market=MARKET)
        for month, value in zip(HISTORY_MONTHS, HISTORY_SCORES)]
POLICY_PASSAGES = [{"source": "POL-002_early_warning_thresholds.md",
                    "text": "Three consecutive monthly declines (synthetic demonstration)."}]
CLAIM_SCOPE = "score_bin_warning_signal_decline_events"
SAFE_FALLBACK = "I could not produce a verified analysis"


def declared_claims():
    return {
        "answer": "UNPUBLISHED DRAFT: administrative warning registered; deny the loan!",
        "score_claims": [
            {"account_id": ACCOUNT, "period": PERIOD, "metric": "score", "value": 271, "market": MARKET},
            {"account_id": ACCOUNT, "period": PERIOD, "metric": "bin", "value": 6, "market": MARKET},
        ],
        "policy_claims": [
            {"field": "warning_signal_status", "value": "triggered",
             "account_id": ACCOUNT, "as_of_period": PERIOD, "market": MARKET},
            {"field": "raw_event_count.consecutive_declines", "value": 1,
             "account_id": ACCOUNT, "as_of_period": PERIOD, "market": MARKET},
        ],
        "limitations": [],
    }


def event_evidence():
    return {
        "window_start": "2025-02-01", "window_end": PERIOD,
        "events": [{"criterion": "consecutive_declines", "period": "2025-03-01",
                    "evidence_periods": HISTORY_MONTHS[:4], "review_state": "eligible"}],
        "data_quality_flags": [], "policy_sources": ["POL-002", "POL-005"],
    }


def verified_audit(data=None):
    """An independently verified audit fixture; not generated by any LLM."""
    obj = copy.deepcopy(declared_claims() if data is None else data)
    checks = []
    for claim in obj["policy_claims"]:
        checks.append({
            "status": "passed", "claim": claim,
            "audit": {
                "status": "passed", "account_id": ACCOUNT,
                "as_of_period": PERIOD, "market": MARKET,
                "unchecked_claims": [],
                "checks": [{"field": claim["field"],
                            "claimed": claim["value"], "expected": claim["value"],
                            "context_matches": True, "value_matches": True,
                            "passed": True}],
                "evidence": event_evidence(),
            },
        })
    return {
        "status": "passed", "schema": {"status": "passed"},
        "answer": obj["answer"], "issues": [], "limitations": obj["limitations"],
        "narrative": {"coverage_method": "llm_draft_excluded"},
        "numeric": {"status": "passed", "checks": [
            {"status": "passed", "claim": claim,
             "context_grounded": True, "value_grounded": True}
            for claim in obj["score_claims"]]},
        "policy": {"status": "passed", "checks": checks},
    }


def evidence():
    return [
        {"tool_name": "get_history", "arguments": {"account_id": ACCOUNT},
         "result": copy.deepcopy(ROWS)},
        {"tool_name": "retrieve_policy", "arguments": {"query": "POL-002"},
         "result": copy.deepcopy(POLICY_PASSAGES)},
    ]


def render(audit=None):
    return compose_verified_full_narrative(
        verified_audit() if audit is None else audit,
        evidence(), account_id=ACCOUNT, as_of_period=PERIOD, market=MARKET,
    )


class PromptIntercept(Exception):
    """Stop execution before the model/provider or any tool is called."""


class PromptCapture:
    def __init__(self):
        self.messages = None

    def chat(self, *, messages, tools):
        self.messages = messages
        raise PromptIntercept


def capture_scope(scope, *, publication_mode="claims_first"):
    provider = PromptCapture()
    kwargs = {"verbose": False, "publication_mode": publication_mode}
    if publication_mode == "claims_first":
        kwargs.update(
            claim_scope=scope, expected_account_id=ACCOUNT,
            expected_period=PERIOD,
            expected_market=3 if scope == "grace_decline_events" else MARKET,
        )
        if scope == "grace_decline_events":
            kwargs.update(site_onboarded_period="2024-05-01",
                          last_exception_review_period="2025-04-01")
    with pytest.raises(PromptIntercept):
        agent.run_agent("Check the requested score trajectory.", provider, **kwargs)
    return provider.messages[0]["content"]


